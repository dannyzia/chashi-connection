const নামেরঅ্যালিয়াস: Record<string, string> = { 'নারায়াণগঞ্জ': 'নারায়ণগঞ্জ' };

// ডেটাসেটের কী-গুলো NFKC-নরমালাইজড — এখানকার নামও লুকআপের আগে একইভাবে নরমালাইজ করা হয়
// (import-locations.mjs-এর norm-এর সাথে হুবহু এক)।
function norm(s: string): string {
  const n = s
    .normalize('NFKC')
    .replace(/[\u200B\u200C\u200D\uFEFF]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
  return Object.prototype.hasOwnProperty.call(নামেরঅ্যালিয়াস, n) ? নামেরঅ্যালিয়াস[n] : n;
}

