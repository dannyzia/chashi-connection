export function জেলাতালিকা(বিভাগনাম: string): string[] {
  return বিভাগসমূহ.find((বি) => বি.নাম === বিভাগনাম)?.জেলাসমূহ.map((জে) => জে.নাম) ?? [];
}

export function উপজেলাতালিকা(বিভাগনাম: string, জেলানাম: string): string[] {
  return উপজেলাগাছ[norm(বিভাগনাম)]?.[norm(জেলানাম)] ?? [];
}

export function ইউনিয়নতালিকা(বিভাগনাম: string, জেলানাম: string, উপজেলানাম: string): string[] {
  return ইউনিয়নগাছ[norm(বিভাগনাম)]?.[norm(জেলানাম)]?.[norm(উপজেলানাম)] ?? [];
}

// দূরত্ব-ব্যান্ড সাজানোর জন্য (PRD §৬): নির্বাচিত জেলার কেন্দ্র-স্থানাঙ্ক
export function জেলাস্থানাঙ্ক(বিভাগনাম: string, জেলানাম: string): { lat: number; lng: number } {
  const জে = বিভাগসমূহ.find((বি) => বি.নাম === বিভাগনাম)?.জেলাসমূহ.find((জ) => জ.নাম === জেলানাম);
  if (জে && জে.lat) return { lat: জে.lat, lng: জে.lng };
  const বি = বিভাগসমূহ.find((ব) => ব.নাম === বিভাগনাম);
  return বি ? { lat: বি.lat, lng: বি.lng } : { lat: 23.8103, lng: 90.4125 }; // ঢাকা ফলব্যাক
}
