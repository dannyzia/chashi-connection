// পিআরডি §৯.২ — লোকালিটি-প্রথম ফিড।
// নিয়ম ১: ব্যান্ড সবসময় আগে — ব্যান্ড ১ কখনো ব্যান্ড ২-এর নিচে যাবে না।
// নিয়ম ২: ব্যান্ডের ভেতরে নতুন পোস্ট আগে।
// নিয়র ৩: ছবি-ছাড়া পোস্ট ব্যান্ডের শীর্ষ ৩ অবস্থানে থাকতে পারবে না (পিআরডি §৮.২)।
// প্রচার-বাড়তি (boost) MVP-তে নেই; ভবিষ্যতে এলে তা ব্যান্ডের *ভেতরের* টাইব্রেকার হবে, ব্যান্ড অগ্রাধিকার কখনো ভাঙবে না।
import { ব্যান্ডসীমা } from './dist';

export interface স্থানাঙ্ক { lat: number; lng: number; }

export interface ফিডআইটেম {
  id: string;
  শিরোনাম: string;
  দাম: number;
  একক: string;
  পরিমাণ: number;
  বিভাগ: string;
  ছবিআছে: boolean;
  ছবি?: string; // সংকুচিত থাম্বনেইল (dataURL) — অফলাইন ক্যাশে থাকে
  সৃষ্টিসময়: number;
  বিক্রেতানাম: string;
  বিক্রেতালেবেল: string;
  যাচাইকৃত: boolean;
  স্থান: স্থানাঙ্ক;
  পোস্টপ্রকার: 'বিক্রয়' | 'প্রয়োজন';
  বিক্রিহয়েছে?: boolean;
}

export interface ব্যান্ডগোষ্ঠী {
  ব্যান্ড: number;
  আইটেমসমূহ: ফিডআইটেম[];
}

export function ব্যান্ডসংখ্যা(কিমি: number): number {
  for (let i = 0; i < ব্যান্ডসীমা.length; i++) {
    if (কিমি < ব্যান্ডসীমা[i]) return i + 1;
  }
  return ব্যান্ডসীমা.length + 1;
}

// ব্যান্ড → ব্যান্ডের ভেতরে নতুন আগে → ছবি-ছাড়া শীর্ষ ৩ থেকে বাদ।
export function ফিডব্যান্ডেভাগ(আইটেমসমূহ: ফিডআইটেম[], ব্যবহারকারীস্থান: স্থানাঙ্ক): ব্যান্ডগোষ্ঠী[] {
  const ব্যান্ডমানচিত্র = new Map<number, ফিডআইটেম[]>();
  for (const আ of আইটেমসমূহ) {
    const কিমি = দূরত্ব(ব্যবহারকারীস্থান, আ.স্থান);
    const ব্যান্ড = ব্যান্ডসংখ্যা(কিমি);
    if (!ব্যান্ডমানচিত্র.has(ব্যান্ড)) ব্যান্ডমানচিত্র.set(ব্যান্ড, []);
    ব্যান্ডমানচিত্র.get(ব্যান্ড)!.push(আ);
  }
  const গোষ্ঠীসমূহ: ব্যান্ডগোষ্ঠী[] = [];
  const ব্যান্ডক্রম = [...ব্যান্ডমানচিত্র.keys()].sort((a, b) => a - b);
  for (const ব্যান্ড of ব্যান্ডক্রম) {
    // ব্যান্ডের ভেতরে নতুন আগে
    const বাছাইকরা = ব্যান্ডমানচিত্র.get(ব্যান্ড)!.sort((p, q) => q.সৃষ্টিসময় - p.সৃষ্টিসময়);
    // শীর্ষ ৩ অবস্থানে ছবিআছে নিশ্চিত করুন (ছবি থাকলে)
    const ছবিসহ = বাছাইকরা.filter(আ => আ.ছবিআছে);
    const ছবিছাড়া = বাছাইকরা.filter(আ => !আ.ছবিআছে);
    const শীর্ষ = ছবিসহ.slice(0, 3);
    const শীর্ষআইডি = new Set(শীর্ষ.map(আ => আ.id));
    const বাকিছবিসহ = ছবিসহ.filter(আ => !শীর্ষআইডি.has(আ.id));
    গোষ্ঠীসমূহ.push({ ব্যান্ড, আইটেমসমূহ: [...শীর্ষ, ...বাকিছবিসহ, ...ছবিছাড়া] });
  }
  return গোষ্ঠীসমূহ;
}

// পিআরডি §৬.৮ — অর্ধ-বৃত্তাকার দূরত্ব
export function দূরত্ব(a: স্থানাঙ্ক, b: স্থানাঙ্ক): number {
  const R = 6371;
  const dLat = ((b.lat - a.lat) * Math.PI) / 180;
  const dLng = ((b.lng - a.lng) * Math.PI) / 180;
  const s =
    Math.sin(dLat / 2) ** 2 +
    Math.cos((a.lat * Math.PI) / 180) * Math.cos((b.lat * Math.PI) / 180) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(s));
}
