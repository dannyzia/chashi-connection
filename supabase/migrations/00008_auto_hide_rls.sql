-- ─────────────────────────────────────────────────────────────────────────────
-- ০০০০৮ — আরএলএস-স্তরে স্বয়ংক্রিয়-লুকানো: §১২.৪-এর লুকানো এখন ডেটা-স্তরের সীমা।
-- সূত্র: পিআরডি §১২.৪ (ভুয়া বিজ্ঞাপন/প্রতারণা ≥২ বা স্প্যাম ≥৩ রিপোর্টে লুকানো),
-- সিদ্ধান্ত CHC-D-044, টাস্ক CHC-T-036; ঘাটতিটি পেয়েছে CHC-T-033 (P3)।
--
-- কেন এই ফাইল: ০০০৬-এর ট্রিগার auto_hidden_at বসায়, কিন্তু products_পঠন_সবার-এর
-- শর্ত ছিল কেবল ((NOT hidden) OR (seller_id = auth.uid())) — auto_hidden_at-এর
-- উল্লেখই ছিল না। ফলে স্বয়ংক্রিয়ভাবে লুকানো পণ্য anon কী ও যেকোনো ক্রেতার সরাসরি
-- REST অনুরোধে পড়া যেত; লুকানো টিকত কেবল অ্যাপের ফিড-ফিল্টার স্তরে।
-- anon কী বান্ডেলে বিতরণ হয়, তাই অ্যাপ-স্তরের লুকানো সীমা (enforcement) নয় —
-- এখানে নীতির শর্ত বদলেই সীমা টানা হচ্ছে।
--
-- কী বদলায়: কেবল products_পঠন_সবার (DROP + CREATE, একই TO ভূমিকা:
-- anon, authenticated)। নতুন শর্ত:
--   ((NOT hidden AND auto_hidden_at IS NULL) OR (seller_id = auth.uid()))
--     · anon ও অন্য ক্রেতা — স্বয়ংক্রিয়-লুকানো পণ্যে শূন্য সারি;
--     · বিক্রেতা নিজে — নিজের পণ্য আগের মতোই দেখে (auto_hidden_at সত্ত্বেও);
--     · অ্যাডমিন — আলাদা permissive নীতি products_অ্যাডমিন_পঠন; নীতিগুলো OR হয়,
--       তাই অপারেটরের ব্যাজ ও এক-ক্লিকে প্রকাশ অটুট।
--
-- ⛔ additive নয়, তবে কেবল সংকীর্ণ: একটি SELECT নীতির শর্ত কঠোর হয়। কোনো
-- টেবিল, কলাম, ফাংশন, অন্য নীতি বা অনুমতি বদলায় না; ম্যানুয়াল লুকানো
-- (hidden = true) আগের মতোই কাজ করে। পুনরায় চালানো নিরাপদ
-- (drop-if-exists + create)। ইতিমধ্যে প্রয়োগ করা মাইগ্রেশন সম্পাদনা নিষিদ্ধ —
-- তাই ০০০১-এর মূল নীতিটি এখানে প্রতিস্থাপিত, সেখানে বদলানো হয়নি।
-- ─────────────────────────────────────────────────────────────────────────────

drop policy if exists products_পঠন_সবার on public.products;

create policy products_পঠন_সবার on public.products
  for select
  to anon, authenticated
  using (
    (not hidden and auto_hidden_at is null)
    or seller_id = auth.uid()
  );
